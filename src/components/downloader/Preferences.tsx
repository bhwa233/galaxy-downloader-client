import { useEffect, useState } from 'react'
import { useTranslation } from 'react-i18next'
import { FolderOpen, RefreshCw, Save } from 'lucide-react'
import { Button } from '@/components/ui/button'
import { Card, CardAction, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card'
import { Field, FieldDescription, FieldGroup, FieldLabel, FieldSet, FieldLegend, FieldTitle } from '@/components/ui/field'
import { Input } from '@/components/ui/input'
import { Item, ItemActions, ItemContent, ItemDescription, ItemTitle } from '@/components/ui/item'
import { Progress } from '@/components/ui/progress'
import { Switch } from '@/components/ui/switch'
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs'
import { Choice } from './Choice'
import type { ClientState, Settings } from '../../../shared/contracts'
import type { Send } from '@/App'
import { modelIds } from '../../../shared/processing'

const sections = ['general', 'download', 'files', 'editing', 'processing', 'browser', 'appearance', 'tools'] as const
type Section = typeof sections[number]
export function Preferences({ state, send }: { state: ClientState; send: Send }) {
  const { t } = useTranslation(['settings', 'common'])
  const { t: processText } = useTranslation('processing')
  const [draft, setDraft] = useState(state.settings)
  useEffect(() => { setDraft(current => ({ ...current, theme: state.settings.theme })) }, [state.settings.theme])
  const [languages, setLanguages] = useState(draft.captionLanguages.join(', '))
  const [section, setSection] = useState<Section>('general')
  const [saved, setSaved] = useState(false)
  const [saving, setSaving] = useState(false)
  const patch = (value: Partial<Settings>) => { setDraft(current => ({ ...current, ...value })); setSaved(false) }
  const number = (key: 'concurrency' | 'speedLimit' | 'taskSpeedLimit' | 'retries' | 'timeout' | 'batchLimit' | 'transcriptionConcurrency', label: string, min: number, max: number, hint: string) => <Field>
    <FieldLabel htmlFor={`setting-${key}`}>{label}</FieldLabel>
    <Input id={`setting-${key}`} aria-label={label} type="number" required min={min} max={max} value={draft[key]} onChange={event => patch({ [key]: event.target.valueAsNumber })} />
    <FieldDescription>{hint}</FieldDescription>
  </Field>
  const toggle = (key: 'resumeOnStart' | 'notifications' | 'minimizeToTray' | 'organizeByPlatform' | 'organizeByCollection' | 'saveThumbnail' | 'editSaveThumbnail' | 'embedThumbnailInVideo' | 'embedThumbnailInAudio' | 'subtitleAutoGenerated' | 'subtitleNormalizeOverlaps' | 'keepHistory' | 'verboseLogging' | 'allowControl' | 'kernelAutoUpdate' | 'downloadSubtitles' | 'autoTranscribe' | 'organizeByChannel' | 'embedMetadata' | 'embedChapters', label: string, hint: string) => <Field orientation="horizontal">
    <FieldContentLabel id={`toggle-${key}`} label={label} hint={hint} />
    <Switch aria-labelledby={`toggle-${key}`} checked={draft[key]} onCheckedChange={checked => patch({ [key]: checked })} />
  </Field>
  return <form className="flex flex-1 flex-col" onSubmit={event => { event.preventDefault(); setSaving(true); void send('settings:save', { ...draft, captionLanguages: languages.split(',').map(value => value.trim()).filter(Boolean) }).then(ok => setSaved(Boolean(ok))).finally(() => setSaving(false)) }}>
    <Card className="flex-1">
      <CardHeader>
        <CardTitle>{t('title')}</CardTitle>
        <CardDescription>{t('description')}</CardDescription>
        <CardAction className="flex items-center gap-3">
          <span role="status" className="text-sm text-muted-foreground">{saved ? t('saved') : ''}</span>
          <Button type="submit" disabled={saving}><Save />{saving ? t('saving') : t('save')}</Button>
        </CardAction>
      </CardHeader>
      <CardContent className="flex flex-1 flex-col">
        {/* A side menu read like the app's own sidebar: rows of the same height, the open one filled
            rather than underlined, and a rule between it and the fields it switches. */}
        <Tabs orientation="vertical" value={section} onValueChange={value => setSection(value as Section)} className="flex-1 gap-6">
          <TabsList className="w-44 shrink-0 items-stretch gap-1 self-stretch rounded-none border-r bg-transparent p-0 pr-4">{sections.filter(id => !['editing', 'processing'].includes(id) || draft.workMode === 'edit').map(id =>
            <TabsTrigger key={id} value={id} className="h-9 flex-none justify-start rounded-md border-0 px-3 font-normal hover:bg-muted/60 data-active:bg-muted data-active:font-medium dark:data-active:border-transparent dark:data-active:bg-muted group-data-[variant=default]/tabs-list:data-active:shadow-none">{t(`sections.${id}`)}</TabsTrigger>)}
          </TabsList>
          <TabsContent value="general"><FieldGroup>
            <Choice label={t('general.workMode.label')} value={draft.workMode} onChange={value => patch({ workMode: value as Settings['workMode'] })} options={(['download', 'edit'] as const).map(value => ({ value, label: t(`common:workModes.${value}`) }))} />
            <FieldDescription>{t('general.workMode.hint')}</FieldDescription>
            <Field>
              <FieldLabel>{t('general.saveLocation')}</FieldLabel>
              <Button type="button" variant="outline" className="justify-start overflow-hidden" onClick={() => void send('settings:directory', null)}><FolderOpen /><span className="truncate">{state.settings.downloadDirectory}</span></Button>
              <FieldDescription>{t('general.saveLocationHint')}</FieldDescription>
            </Field>
            {toggle('resumeOnStart', t('general.resumeOnStart.label'), t('general.resumeOnStart.hint'))}
            {toggle('notifications', t('general.notifications.label'), t('general.notifications.hint'))}
            {toggle('minimizeToTray', t('general.minimizeToTray.label'), t('general.minimizeToTray.hint'))}
            {toggle('keepHistory', t('general.keepHistory.label'), t('general.keepHistory.hint'))}
          </FieldGroup></TabsContent>
          <TabsContent value="download"><FieldGroup>
            <div className="grid gap-4 sm:grid-cols-2">
              {number('concurrency', t('download.concurrency.label'), 1, 4, t('download.concurrency.hint'))}
              {number('speedLimit', t('download.speedLimit.label'), 0, 1048576, t('download.speedLimit.hint'))}
              {number('taskSpeedLimit', t('download.taskSpeedLimit.label'), 0, 1048576, t('download.taskSpeedLimit.hint'))}
              {number('timeout', t('download.timeout.label'), 5, 300, t('download.timeout.hint'))}
              {number('retries', t('download.retries.label'), 0, 10, t('download.retries.hint'))}
              {number('batchLimit', t('download.batchLimit.label'), 0, 500, t('download.batchLimit.hint'))}
            </div>
          </FieldGroup></TabsContent>
          <TabsContent value="files"><FieldGroup>
            {toggle('downloadSubtitles', processText('attach'), processText('attachHint'))}
            <Field><FieldLabel htmlFor="caption-languages">{processText('defaultLanguage')}</FieldLabel><Input id="caption-languages" value={languages} onChange={event => { setLanguages(event.target.value); setSaved(false) }} /><FieldDescription>{processText('languageHint')}</FieldDescription></Field>
            {toggle('subtitleAutoGenerated', t('files.subtitles.autoGenerated.label'), t('files.subtitles.autoGenerated.hint'))}
            {toggle('organizeByChannel', processText('channel'), processText('channel'))}
            <Field><FieldLabel htmlFor="filename-template">{processText('template')}</FieldLabel><Input id="filename-template" value={draft.customFilenameTemplate} onChange={event => patch({ customFilenameTemplate: event.target.value })} maxLength={300} /><FieldDescription>{processText('templateHint')}</FieldDescription></Field>
            <Choice label={t('files.naming.label')} value={draft.filenameTemplate} onChange={value => patch({ filenameTemplate: value as Settings['filenameTemplate'] })} options={[{ value: 'title-id', label: t('files.naming.titleId') }, { value: 'id-title', label: t('files.naming.idTitle') }, { value: 'date-title-id', label: t('files.naming.dateTitleId') }]} />
            <FieldDescription>{t('files.namingHint')}</FieldDescription>
            {toggle('organizeByPlatform', t('files.organizeByPlatform.label'), t('files.organizeByPlatform.hint'))}
            {toggle('organizeByCollection', t('files.organizeByCollection.label'), t('files.organizeByCollection.hint'))}
            <div className="grid gap-4 sm:grid-cols-2">
              <Choice label={t('files.videoQuality.label')} value={draft.workMode === 'edit' ? draft.editVideoQuality : draft.videoQuality} onChange={value => patch(draft.workMode === 'edit' ? { editVideoQuality: value as Settings['videoQuality'] } : { videoQuality: value as Settings['videoQuality'] })} options={[{ value: 'best', label: t('files.videoQuality.best') }, ...['1080', '720', '480'].map(value => ({ value, label: t('files.videoQuality.upTo', { height: value }) }))]} />
            </div>
            <FieldDescription>{t('files.mergeHint')}</FieldDescription>
            <FieldSet>
              <FieldLegend variant="label">{t('files.cover.legend')}</FieldLegend>
              <FieldGroup className="gap-4">
                {toggle(draft.workMode === 'edit' ? 'editSaveThumbnail' : 'saveThumbnail', t('files.cover.save.label'), t('files.cover.save.hint'))}
                {draft.workMode === 'edit' && <Choice label={t('files.cover.format.label')} value={draft.thumbnailFormat} onChange={value => patch({ thumbnailFormat: value as Settings['thumbnailFormat'] })} options={[{ value: 'original', label: t('files.cover.format.original') }, { value: 'jpg', label: t('files.cover.format.jpg') }]} />}
                <FieldDescription>{t('files.cover.hint')}</FieldDescription>
              </FieldGroup>
            </FieldSet>
          </FieldGroup></TabsContent>
          {draft.workMode === 'edit' && <TabsContent value="editing"><FieldGroup>
            <FieldDescription>{t('editing.hint')}</FieldDescription>
            <Choice label={t('editing.outputFormat')} value={draft.outputFormat} onChange={value => patch({ outputFormat: value as Settings['outputFormat'] })} options={[{ value: 'original', label: t('editing.originalFormat') }, { value: 'mp4', label: 'MP4' }, { value: 'mkv', label: 'MKV' }]} />
            <Choice label={t('editing.outputResolution')} value={draft.outputResolution} onChange={value => patch({ outputResolution: value as Settings['outputResolution'] })} options={[{ value: 'original', label: t('editing.originalResolution') }, ...['2160', '1440', '1080', '720', '480'].map(value => ({ value, label: `${value}p` }))]} />
            <FieldDescription>{t('editing.resolutionHint')}</FieldDescription>
            <FieldSet>
              <FieldLegend variant="label">{t('files.cover.legend')}</FieldLegend>
              <FieldGroup>
                {toggle('embedThumbnailInVideo', t('files.cover.embedVideo.label'), t('files.cover.embedVideo.hint'))}
                {toggle('embedThumbnailInAudio', t('files.cover.embedAudio.label'), t('files.cover.embedAudio.hint'))}
              </FieldGroup>
            </FieldSet>
          </FieldGroup></TabsContent>}
          {draft.workMode === 'edit' && <TabsContent value="processing"><FieldGroup>
            <FieldDescription>{processText('offline')}</FieldDescription>
            <Choice label={processText('model')} value={draft.transcriptionModel} onChange={value => patch({ transcriptionModel: value as Settings['transcriptionModel'] })} options={modelIds.map(value => ({ value, label: state.processing?.models.find(model => model.id === value)?.name || value }))} />
            {number('transcriptionConcurrency', processText('concurrency'), 1, 4, processText('offline'))}
            {toggle('autoTranscribe', processText('automatic'), processText('automaticHint'))}
            {toggle('embedMetadata', processText('metadata'), processText('metadata'))}
            {toggle('embedChapters', processText('chapters'), processText('chapters'))}
          </FieldGroup></TabsContent>}
          <TabsContent value="browser"><FieldGroup>
            <Item variant="muted">
              <ItemContent>
                <ItemTitle>{t('browser.systemTitle')}</ItemTitle>
                <ItemDescription className="whitespace-normal">{t('browser.systemDescription', { browser: state.profiles.find(profile => profile.id === state.settings.browserProfileId)?.label || t('browser.noBrowser') })}</ItemDescription>
              </ItemContent>
            </Item>
            <Button type="button" variant="outline" className="w-fit" onClick={() => void send('browser:refresh', null)}><RefreshCw />{t('browser.redetect')}</Button>
            <Item variant="muted">
              <ItemContent>
                <ItemTitle>{state.browser.sites ? t('browser.sessions', { count: state.browser.sites }) : t('browser.noSessions')}</ItemTitle>
                <ItemDescription className="whitespace-normal">{t('browser.sessionsHint')}</ItemDescription>
              </ItemContent>
            </Item>
            <div className="flex flex-wrap gap-2">
              <Button type="button" variant="outline" onClick={() => void send('browser:login', { url: '' })}>{t('common:openLogin')}</Button>
              <Button type="button" variant="outline" onClick={() => void send('browser:clear', null)}>{t('browser.clearSessions')}</Button>
            </div>
          </FieldGroup></TabsContent>
          <TabsContent value="appearance"><FieldGroup>
            {/* Labelled in both languages and applied at once, so whoever switched to the one they do not
                read can still find the way back. */}
            <Choice label="语言 · Language" value={state.settings.locale} onChange={value => { patch({ locale: value as Settings['locale'] }); void send('settings:save', { ...state.settings, locale: value as Settings['locale'] }) }} options={[{ value: 'zh', label: '中文' }, { value: 'en', label: 'English' }]} />
            <Choice label={t('appearance.theme.label')} value={draft.theme} onChange={value => patch({ theme: value as Settings['theme'] })} options={[{ value: 'system', label: t('appearance.theme.system') }, { value: 'light', label: t('appearance.theme.light') }, { value: 'dark', label: t('appearance.theme.dark') }]} />
            <Choice label={t('appearance.resultView.label')} value={draft.resultView} onChange={value => patch({ resultView: value as Settings['resultView'] })} options={[{ value: 'auto', label: t('appearance.resultView.auto') }, { value: 'list', label: t('appearance.resultView.list') }, { value: 'grid', label: t('appearance.resultView.grid') }]} />
            <Choice label={t('appearance.density.label')} value={draft.density} onChange={value => patch({ density: value as Settings['density'] })} options={[{ value: 'comfortable', label: t('appearance.density.comfortable') }, { value: 'compact', label: t('appearance.density.compact') }]} />
          </FieldGroup></TabsContent>
          <TabsContent value="tools"><FieldGroup>
            {toggle('kernelAutoUpdate', processText('kernelAuto'), processText('kernelHint'))}
            <Item variant="muted"><ItemContent><ItemTitle>{processText('kernel')}</ItemTitle><ItemDescription>{state.kernel?.version || state.tools.engine.version} · {processText(`kernelStatuses.${state.kernel?.status || 'idle'}`)}</ItemDescription>{state.kernel?.error && <ItemDescription>{state.kernel.error}</ItemDescription>}</ItemContent><ItemActions><Button type="button" variant="outline" disabled={state.kernel?.status === 'checking' || state.kernel?.status === 'downloading'} onClick={() => void send('kernel:check', null)}>{processText('kernelCheck')}</Button>{state.kernel?.previous && <Button type="button" variant="outline" disabled={state.kernel.status !== 'idle' && state.kernel.status !== 'error'} onClick={() => void send('kernel:rollback', null)}>{processText('kernelRollback')}</Button>}</ItemActions></Item>
            {state.kernel?.status === 'downloading' && <Progress value={(state.kernel.progress || 0) * 100} />}
            <Item variant="muted">
              <ItemContent>
                <ItemTitle>yt-dlp</ItemTitle>
                <ItemDescription className="break-all whitespace-normal">{state.tools.engine.available ? state.tools.engine.version : state.tools.engine.error || t('tools.checking')}</ItemDescription>
                <ItemTitle>FFmpeg</ItemTitle>
                <ItemDescription className="break-all whitespace-normal">{state.tools.ffmpeg.available ? state.tools.ffmpeg.version : state.tools.ffmpeg.error || t('tools.checking')}</ItemDescription>
                <ItemDescription>{t('tools.localHint')}</ItemDescription>
              </ItemContent>
            </Item>
            <div className="flex flex-wrap gap-2">
              <Button type="button" variant="outline" onClick={() => void send('tools:check', null)}>{t('tools.checkTools')}</Button>
              <Button type="button" variant="outline" disabled={['checking', 'downloading'].includes(state.update.status)} onClick={() => void send('update:check', null)}>{t('tools.checkUpdate')}</Button>
              {state.update.status === 'available' && <Button type="button" onClick={() => void send('update:download', null)}>{t('tools.downloadUpdate', { version: state.update.version })}</Button>}
              {state.update.status === 'ready' && <Button type="button" onClick={() => void send('update:install', null)}>{t('tools.installUpdate')}</Button>}
            </div>
            {state.update.status === 'downloading' && <Progress value={state.update.progress ?? 0} />}
            {state.update.message && <p className="text-sm">{state.update.message}</p>}
            {toggle('verboseLogging', t('tools.verboseLogging.label'), t('tools.verboseLogging.hint'))}
            {toggle('allowControl', t('tools.allowControl.label'), t('tools.allowControl.hint'))}
            {/* Installed at once rather than on 保存设置: it writes files and the PATH, not a setting. */}
            <Item variant="muted">
              <ItemContent>
                <ItemTitle>{t('tools.commandLine.title')}</ItemTitle>
                <ItemDescription className="whitespace-normal">{state.commandLine.installed ? t('tools.commandLine.installed', { path: state.commandLine.launcher }) : t('tools.commandLine.hint')}</ItemDescription>
                {state.commandLine.installed && !state.commandLine.onPath && <ItemDescription className="whitespace-normal">{t('tools.commandLine.notOnPath')}</ItemDescription>}
              </ItemContent>
              <ItemActions>
                <Button type="button" variant="outline" onClick={() => void send(state.commandLine.installed ? 'cli:uninstall' : 'cli:install', null)}>{state.commandLine.installed ? t('tools.commandLine.uninstall') : t('tools.commandLine.install')}</Button>
              </ItemActions>
            </Item>
            <div className="flex flex-wrap gap-2">
              <Button type="button" variant="outline" onClick={() => void send('logs:open', null)}>{t('tools.openLogs')}</Button>
              <Button type="button" variant="outline" onClick={() => void send('logs:export', null)}>{t('tools.exportLogs')}</Button>
            </div>
          </FieldGroup></TabsContent>
        </Tabs>
      </CardContent>
    </Card>
  </form>
}
function FieldContentLabel({ id, label, hint }: { id: string; label: string; hint: string }) {
  return <div className="grid gap-1">
    <FieldTitle id={id}>{label}</FieldTitle>
    <FieldDescription>{hint}</FieldDescription>
  </div>
}
